<#
.SYNOPSIS
DEVELOPER-ONLY (tools\dev, never shipped, never referenced by the product). Builds the static demo site (docs/DEMO-SITE.md) into -Output
(default out\site): the shell from site\, the design tokens generated from the window's theme, and per scenario a view model computed by
the WINDOW'S OWN pure helpers (score, areas, actions, headline, findings, details with the walkthrough, map layout) from the results the
real engine produced on the simulated world, plus the replay stream.

.DESCRIPTION
-TokensOnly writes only site\assets\tokens.css (committed; tests\DemoSite.Tests.ps1 fails when it drifts from the theme).
-SkipGenerate reuses out\site-data instead of running every scenario again.
Writes only under out\ (and, with -TokensOnly, site\assets\tokens.css).
#>
[CmdletBinding()]
param(
    [string]$Output = '',
    [switch]$SkipGenerate,
    [switch]$TokensOnly,
    [string]$TokensPath = '',
    [string]$DataRoot = '',
    [string]$Commit = ''
)
$ErrorActionPreference = 'Stop'
$here = Split-Path -Parent $MyInvocation.MyCommand.Path
$repo = Split-Path (Split-Path (Split-Path $here))
$gui = Join-Path $repo 'src\Gui'
$utf8 = New-Object System.Text.UTF8Encoding($false)

function ConvertTo-MspkiCssName { param([string]$Key) return ('--' + (($Key -replace '^B\.', 'c-') -creplace '([a-z0-9])([A-Z])', '$1-$2').ToLowerInvariant()) }

function Get-MspkiDemoTokenCss {
    <# The CSS custom properties of the window's design language: both palettes (light by default, dark with prefers-color-scheme or
       data-theme), the type ramp of the theme's text styles, radii and motion. #>
    $pal = {
        param([string]$File)
        $x = [System.IO.File]::ReadAllText((Join-Path $gui $File))
        $out = [ordered]@{}
        foreach ($m in [regex]::Matches($x, '<SolidColorBrush x:Key="(B\.[A-Za-z0-9]+)" Color="(#[0-9A-Fa-f]{6,8})"')) {
            $c = $m.Groups[2].Value
            if ($c.Length -eq 9) { $a = [Convert]::ToInt32($c.Substring(1, 2), 16) / 255; $c = 'rgba({0}, {1}, {2}, {3})' -f [Convert]::ToInt32($c.Substring(3, 2), 16), [Convert]::ToInt32($c.Substring(5, 2), 16), [Convert]::ToInt32($c.Substring(7, 2), 16), [math]::Round($a, 3).ToString([Globalization.CultureInfo]::InvariantCulture) }
            $out[(ConvertTo-MspkiCssName $m.Groups[1].Value)] = $c.ToUpperInvariant() -replace 'RGBA', 'rgba'
        }
        $out
    }
    $light = & $pal 'Palette.Light.xaml'
    $dark = & $pal 'Palette.Dark.xaml'
    $theme = [System.IO.File]::ReadAllText((Join-Path $gui 'Theme.xaml'))
    $ramp = [ordered]@{}
    foreach ($m in [regex]::Matches($theme, '(?s)<Style x:Key="([A-Za-z0-9]+)" TargetType="TextBlock"[^>]*>(.*?)</Style>')) {
        $fs = [regex]::Match($m.Groups[2].Value, 'Property="FontSize" Value="([0-9.]+)"')
        if (-not $fs.Success) { continue }
        $fw = [regex]::Match($m.Groups[2].Value, 'Property="FontWeight" Value="([A-Za-z]+)"')
        $w = $(switch ($fw.Groups[1].Value) { 'SemiBold' { 600 } 'Bold' { 700 } 'Light' { 300 } default { 400 } })
        $ramp[('--fs-' + $m.Groups[1].Value.ToLowerInvariant())] = '{0}px' -f $fs.Groups[1].Value
        $ramp[('--fw-' + $m.Groups[1].Value.ToLowerInvariant())] = [string]$w
    }
    $sb = New-Object System.Text.StringBuilder
    [void]$sb.AppendLine('/* GENERATED by tools/dev/demo-site/Build-MspkiDemoSite.ps1 -TokensOnly from src/Gui/Palette.Light.xaml, Palette.Dark.xaml and Theme.xaml.')
    [void]$sb.AppendLine('   Do not edit: tests/DemoSite.Tests.ps1 fails when this file drifts from the window''s theme. */')
    [void]$sb.AppendLine(':root {')
    [void]$sb.AppendLine('  --font: "Segoe UI Variable Text", "Segoe UI", system-ui, -apple-system, "Helvetica Neue", Arial, sans-serif;')
    [void]$sb.AppendLine('  --mono: Consolas, "Cascadia Mono", ui-monospace, "SFMono-Regular", Menlo, monospace;')
    [void]$sb.AppendLine('  --r-s: 4px; --r-m: 8px; --r-l: 16px; --pane-r: 6px;')
    [void]$sb.AppendLine('  --t-fast: 120ms; --t-med: 250ms; --t-slow: 600ms; --ease: cubic-bezier(0.1, 0.9, 0.2, 1);')
    foreach ($k in $ramp.Keys) { [void]$sb.AppendLine(('  {0}: {1};' -f $k, $ramp[$k])) }
    [void]$sb.AppendLine('  color-scheme: light;')
    foreach ($k in $light.Keys) { [void]$sb.AppendLine(('  {0}: {1};' -f $k, $light[$k])) }
    [void]$sb.AppendLine('}')
    $darkBlock = @(foreach ($k in $dark.Keys) { '    {0}: {1};' -f $k, $dark[$k] })
    [void]$sb.AppendLine('@media (prefers-color-scheme: dark) {')
    [void]$sb.AppendLine('  :root:not([data-theme="light"]) {')
    [void]$sb.AppendLine('    color-scheme: dark;')
    foreach ($l in $darkBlock) { [void]$sb.AppendLine($l) }
    [void]$sb.AppendLine('  }')
    [void]$sb.AppendLine('}')
    [void]$sb.AppendLine(':root[data-theme="dark"] {')
    [void]$sb.AppendLine('  color-scheme: dark;')
    foreach ($l in $darkBlock) { [void]$sb.AppendLine($l.Substring(2)) }
    [void]$sb.AppendLine('}')
    return $sb.ToString()
}

$tokenFile = $(if ($TokensPath) { $TokensPath } else { Join-Path $repo 'site\assets\tokens.css' })
if ($TokensOnly) { [System.IO.File]::WriteAllText($tokenFile, (Get-MspkiDemoTokenCss), $utf8); Write-Host ('Wrote {0}' -f $tokenFile); return }

if (-not $Output) { $Output = Join-Path $repo 'out\site' }
$outFull = [System.IO.Path]::GetFullPath($Output)
$outRoot = [System.IO.Path]::GetFullPath((Join-Path $repo 'out')) + '\'
if (-not $outFull.StartsWith($outRoot, [StringComparison]::OrdinalIgnoreCase)) { throw ('The site is built only under {0}' -f $outRoot) }
$dataRoot = $(if ($DataRoot) { [System.IO.Path]::GetFullPath($DataRoot) } else { Join-Path $repo 'out\site-data' })
if (-not $SkipGenerate) { & (Join-Path $here 'Invoke-MspkiScenario.ps1') -Scenario all -Output $dataRoot -Commit $Commit | Out-Null }

Import-Module (Join-Path $repo 'src\MspkiHealthCheck.psd1') -Force
foreach ($n in 'GuiModel.ps1', 'GuiView.ps1', 'GuiEntity.ps1', 'GuiMission.ps1', 'GuiMap.ps1') { . (Join-Path $gui $n) }

function Get-MspkiDemoView {
    <# One scenario's view model: what the window shows for the same results.json, computed with the window's own helpers. #>
    param([string]$Folder)
    $m = Get-Content -Raw -LiteralPath (Join-Path $Folder 'manifest.json') | ConvertFrom-Json
    $data = Read-MspkiGuiResults -Path (Join-Path $Folder 'results.json')
    $f = @($data.Findings | Where-Object { $null -ne $_ })
    $completed = [bool]$data.RunInfo.Completed
    $hasCa = (@($data.Inventory.EnterpriseCAs | Where-Object { $null -ne $_ }).Count -gt 0)
    $score = Get-MspkiGuiHealthScore -Findings $f -Completed $completed -HasCa $hasCa
    $actions = Get-MspkiGuiNextAction -Findings $f -Max 1000
    $summary = Get-MspkiGuiSummary -RunInfo $data.RunInfo -Inventory $data.Inventory -Findings $f -ExitCode $data.ExitCode
    $headline = Get-MspkiGuiHeadline -Health $summary.Health -Actions $actions -Score $score -Completed $completed -HasCa $hasCa -AsOf ''
    $rows = New-Object System.Collections.ArrayList
    foreach ($r in (ConvertTo-MspkiGuiRowList -Findings $f)) { [void]$rows.Add($r) }
    $details = [ordered]@{}
    foreach ($x in $f) {
        $d = Get-MspkiGuiFindingDetail -Finding $x
        $causes = @(foreach ($c in @($d.DiagCauses)) {
            [ordered]@{ rank = [string]$c.Rank; heading = [string]$c.Heading; cause = [string]$c.Cause; likelihood = [string]$c.Likelihood; isTop = [bool]$c.IsTop
                observed = [bool]$c.Observed; because = [string]$c.BecauseText; hint = [string]$c.HintText; confirm = [string]$c.ConfirmText
                fixOwner = [string]$c.FixOwner; fixLabel = [string]$c.FixLabel; fix = [string]$c.FixText
                checks = @(foreach ($k in @($c.Checks)) { [ordered]@{ text = [string]$k.Text; command = [bool]$k.IsCommand } }) }
        })
        $details[[string]$x.Id] = [ordered]@{
            title = [string]$d.Title; message = [string]$d.Message; status = [string]$d.Status; statusText = [string]$d.StatusPill.Text; statusTone = [string]$d.StatusPill.Tone
            severity = [string]$d.SeverityPill.Text; confidence = [string]$d.ConfidencePill.Text
            evidence = @($d.Evidence | ForEach-Object { [string]$_ }); remediation = [string]$d.Remediation; notes = [string]$d.Notes
            sources = @($d.Sources | ForEach-Object { [string]$_ })
            diag = $(if ($d.HasDiagnosis) { [ordered]@{ title = [string]$d.DiagTitle; summary = [string]$d.DiagSummary; basis = [string]$d.DiagBasis; checkNote = [string]$d.CheckNote
                    causes = $causes; sources = @($d.DiagSourceItems | ForEach-Object { [ordered]@{ title = [string]$_.Title; url = [string]$_.Url } }) } } else { $null })
        }
    }
    $ix = New-MspkiGuiGraphIndex -Graph $data.Graph -Findings $f
    $st = @{}; foreach ($x in $f) { $st[[string]$x.Id] = [string]$x.Status }
    $job = Invoke-MspkiGuiMapJob -Request @{ Kind = 'Page'; Gen = 1; Options = @{ Threshold = 120 } } -Index $ix -Status $st -Cache @{}
    $map = $null
    if (-not $job.Empty) {
        $v = $job.View
        $map = [ordered]@{ width = [int][math]::Ceiling([double]$v.Width); height = [int][math]::Ceiling([double]$v.Height)
            nodes = @(foreach ($n in $v.Nodes) { [ordered]@{ id = [string]$n.Id; entity = [string]$n.EntityId; kind = [string]$n.Kind; label = [string]$n.Label; sub = [string]$n.Sub
                    tone = [string]$n.Tone; x = [int][math]::Round([double]$n.X); y = [int][math]::Round([double]$n.Y); layer = [int]$n.Layer; full = [string]$n.FullName
                    count = $(if ($null -ne $n.Count) { [int]$n.Count } else { 0 }); where = [string]$n.WhereText } })
            links = @(foreach ($l in $v.Links) { [ordered]@{ from = [string]$l.From; to = [string]$l.To; kind = [string]$l.Kind; tone = [string]$l.Tone; text = [string]$l.Text } }) }
    }
    $events = Get-Content -Raw -LiteralPath (Join-Path $Folder 'events.json') | ConvertFrom-Json
    $replay = @(foreach ($e in $events) {
        switch ([string]$e.Kind) {
            'Entity' { [ordered]@{ t = [int64]$e.T; k = 'e'; id = [string]$e.Id; type = [string]$e.Type; name = [string]$e.Name } }
            'Probe' { [ordered]@{ t = [int64]$e.T; k = 'p'; id = [string]$e.Id; probe = [string]$e.Probe; phase = [string]$e.Phase; outcome = [string]$e.Outcome } }
            'StageStart' { [ordered]@{ t = [int64]$e.T; k = 's'; text = (Get-MspkiGuiStageLabel -Stage ([string]$e.Text)) } }
        }
    })
    return [ordered]@{
        id = [string]$m.Scenario; title = [string]$m.Title; summary = [string]$m.Summary
        manifest = [ordered]@{ tool = [string]$m.Tool; version = [string]$m.ToolVersion; commit = [string]$m.Commit; demoClock = [string]$m.DemoClock; simulatedSeconds = $m.SimulatedSeconds; note = [string]$m.Note }
        run = [ordered]@{ forest = [string]$summary.Forest; domain = [string]$summary.Domain; dc = [string]$summary.DomainController; computer = [string]$summary.Computer; user = [string]$summary.User
            started = [string]$summary.Started; duration = [string]$summary.Duration; findings = $f.Count; completed = $completed }
        headline = [string]$headline
        score = [ordered]@{ has = [bool]$score.HasScore; overall = $score.Overall; text = [string]$score.OverallText; band = [string]$score.Band; tone = [string]$score.Tone
            partial = [bool]$score.Partial; partialText = [string]$score.PartialText; how = [string]$score.HowText; held = [string]$score.HeldText; reason = [string]$score.Reason
            areas = @(foreach ($a in @($score.Areas)) { [ordered]@{ key = [string]$a.Key; name = [string]$a.Name; score = $a.Score; text = [string]$a.ScoreText; tone = [string]$a.Tone
                    detail = [string]$a.Detail; fail = [int]$a.Fail; warn = [int]$a.Warn; notChecked = [int]$a.NotChecked; count = [int]$a.Count; partial = [bool]$a.Partial } }) }
        actions = [ordered]@{ total = [int]$actions.Total
            items = @(foreach ($a in @($actions.Items)) { [ordered]@{ title = [string]$a.Title; cause = [string]$a.Cause; observed = [string]$a.ObservedText; count = [string]$a.CountText
                    area = [string]$a.AreaName; tone = [string]$a.Tone; status = [string]$a.StatusText; tag = [string]$a.Tag; rank = [string]$a.RankText } }) }
        findings = @(foreach ($r in $rows) { [ordered]@{ id = [string]$r.Id; status = [string]$r.StatusKey; word = [string]$r.StatusWord; severity = [string]$r.SeverityText; category = [string]$r.Category
                title = [string]$r.Title; target = [string]$r.TargetText; message = [string]$r.Message; confidence = [string]$r.Confidence; code = [string]$r.StatusCode } })
        details = $details; map = $map; replay = $replay
    }
}

# Shell, tokens and data.
if (Test-Path -LiteralPath $outFull) { Remove-Item -LiteralPath $outFull -Recurse -Force }
[void](New-Item -ItemType Directory -Path $outFull -Force)
Copy-Item -Path (Join-Path $repo 'site\*') -Destination $outFull -Recurse -Exclude 'world'
[System.IO.File]::WriteAllText((Join-Path $outFull 'assets\tokens.css'), (Get-MspkiDemoTokenCss), $utf8)
$index = New-Object System.Collections.ArrayList
$known = @(Get-ChildItem -LiteralPath (Join-Path $repo 'site\world\scenarios') -Filter '*.json' | ForEach-Object { $_.BaseName })
foreach ($d in Get-ChildItem -LiteralPath $dataRoot -Directory | Where-Object { $known -contains $_.Name } | Sort-Object Name) {
    $view = Get-MspkiDemoView -Folder $d.FullName
    $dir = Join-Path $outFull ('data\' + $d.Name)
    [void](New-Item -ItemType Directory -Path $dir -Force)
    [System.IO.File]::WriteAllText((Join-Path $dir 'view.json'), (ConvertTo-Json -InputObject $view -Depth 12 -Compress), $utf8)
    [void]$index.Add([ordered]@{ id = $view.id; title = $view.title; summary = $view.summary; score = $view.score.text; band = $view.score.band; tone = $view.score.tone; headline = $view.headline; findings = $view.run.findings })
}
$order = @('healthy', 'baseline', 'expired-crl', 'rpc-denied', 'ldap-only', 'esc8', 'forged-aia', 'ndes-found', 'renewal-drift', 'mixed-sample')
$sorted = @($index | Sort-Object { $i = [array]::IndexOf($order, $_.id); if ($i -lt 0) { 99 } else { $i } })
$first = Get-Content -Raw -LiteralPath (Join-Path $dataRoot 'baseline\manifest.json') | ConvertFrom-Json
$site = [ordered]@{ version = [string]$first.ToolVersion; commit = [string]$first.Commit; demoClock = [string]$first.DemoClock; scenarios = $sorted }
[System.IO.File]::WriteAllText((Join-Path $outFull 'data\scenarios.json'), (ConvertTo-Json -InputObject $site -Depth 6 -Compress), $utf8)
Write-Host ('Site built in {0} ({1} scenarios)' -f $outFull, $sorted.Count)
